//! | APP-PLY-01 | プレイ入力: レーンは割り当てた物理キーのどれかが押されていれば押下中。割り当ての無いキーは無視 |
//! | APP-PLY-02 | プレイ入力: 1 フレームで渡すレーンの変化（押した・離した）は 1 回まで。残りは次のフレームに回す |
//! | APP-PLY-03 | プレイ: キー音と BGM はそのフレームの時刻で `AudioOutput` に渡す |
//! | APP-PLY-04 | プレイ描画: y = (ノーツの拍 − 今の拍) / 表示拍数。y ≤ 1 のものだけ返し、押下中の LN の始点は 0 で止める |
//! | APP-SKN-01 | LR2 スキン: 画面の開始でタイマー 0、`#STARTINPUT` 後に 1、`#LOADSTART`+`#LOADEND` で 40、譜面の先頭（`#PLAYSTART` 後）で 41 を始める。変わらない条件 32・41・42/43・81・160..164・170/171・172/173 とスキンの条件 |
//! | APP-SKN-02 | LR2 スキン: 判定でタイマー 46、PG/GR なら 50+レーン。最後の判定は条件 241(PG)..246(空POOR)、BD 以下から 1 秒未満は 248、それ以外は 247。地雷は 46 だけ |
//! | APP-SKN-03 | LR2 スキン: 押したらタイマー 100+レーン を始めて 120+レーン を止め、離したら逆。押下中の LN の間は 70+レーン |
//! | APP-SKN-04 | LR2 スキン: 表示 HP（偶数）が増えて 100 未満ならタイマー 42、100 なら 44。途中終了で 3、全ノーツ COMBO で 48、全ノーツを片付けたら 143。条件 230..239 は HP の 10% 帯、240 は 100% |
//! | APP-SKN-05 | LR2 スキン: 数値 100..107・110..115・160..164（スコア・EX・率・コンボ・HP・判定数・BPM・経過/残り時間） |
//! | APP-SKN-06 | LR2 スキン: 描画材料はノーツの判定までの拍数と HP/2。タイマー 140 は 1 拍 = 1000 で小節線ごとに 0 から。BARGRAPH 1・SLIDER 6 は曲の進み具合。小節線は判定までの拍数 |
//! | APP-SKN-07 | LR2 スキン: 表示の追従。スコアは 500ms、HP は差 × 10ms で直線的に新しい値へ（途中で変われば今の表示から） |
//! | APP-SKN-08 | LR2 スキン: 曲の長さ = オブジェクトの時刻 + 音の長さ の最大。過ぎたらタイマー 2、`#FADEOUT` 後に場面を閉じる。途中終了はタイマー 3 から `#CLOSE` |
//! | APP-SKN-09 | LR2 スキン: 皿の角度。回している向きに 720°/s、それ以外はプレイ開始後 360°/s |
//! | APP-SKN-10 | LR2 スキン: 文字列 10 題名・11 副題・12 題名 + 空白 + 副題（副題が無ければ題名）・13 ジャンル・14 アーティスト・15 副アーティスト。空は無し |
