//! | DOM-SKD-14 | LR2 の BGA: タイマー 41 が動いていて条件を満たすとき、層ごとに画像全体を DST に描く。画像の幅が 256 未満なら 幅 × 画像の幅/256 にして中央へ、高さが 256 未満なら 高さ × 画像の高さ/256（上揃え）。1 層目は後ろに α だけ DST の黒（回していなければ）、2 層目以降は描画順キーの次 |
