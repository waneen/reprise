//! # 仕様ルール（テストと 1 対 1 対応）
//! | ID | ルール |
//! |---|---|
//! | DOM-RNG-01 | `LegacyMt` は旧 `sgenrand`（69069 の線形合同法）で状態を初期化した MT19937。同じシードは同じ列 |
//! | DOM-RNG-02 | `get_rand(max)` は `(u32 出力 × (max+1)) >> 32` で `0..=max` を返す（DxLib `GetRand`） |
//! | DOM-RNG-03 | レーン RANDOM: `c = 1..keys-1` について `a = c + get_rand(keys-c)` と入れ替える（皿は対象外） |
//! | DOM-RNG-04 | 配置番号: 位置 i に元レーン t[i] が来るとき Σ i·10^(keys−t[i]) |
//! | DOM-RNG-05 | OpenLR2 のシード対応表と全件一致（対応表は同梱せず、手元で任意実行） |
//! | DOM-CHT-01 | 譜面の同一性（`ChartHash` の等価・ハッシュ）は MD5 だけで決める（LR2 の記録は SHA-256 を持たない） |
//! | DOM-TIM-01 | 拍→時刻: 初期 BPM（未指定・0 以下は 130）で 1 拍 = 60/BPM 秒 |
//! | DOM-TIM-02 | BPM 変化はその拍以降に効く。同じ拍に複数あれば後勝ち |
//! | DOM-TIM-03 | STOP の拍の時刻は停止前、以降は「停止拍数 × 60/BPM」秒遅れる。同じ拍の BPM 変化の後に評価し、同じ拍の STOP は加算 |
//! | DOM-TIM-04 | BPM ≤ 0 の変化は無視する（LR2 実機の挙動は未検証） |
//! | DOM-TIM-05 | 時刻→拍は拍→時刻の逆。停止中は停止している拍 |
//! | DOM-TIM-06 | 時刻の BPM はその時刻を含む区間の BPM（停止中は停止した拍の BPM、0 より前は初期 BPM） |
//! | DOM-TIM-07 | 止まっていない経過時間 = 時刻 − それまでに止まった時間（停止中は停止を始めた時刻のまま） |
//! | DOM-JDG-01 | 押下の判定: Δ = 押下 − ノーツ（正 = 遅い）が PG→GR→GD→BD の順に最初に入った幅（両端含む）。どれにも入らず空POOR の幅なら空POOR、それも外ならそのノーツに作用しない |
//! | DOM-JDG-02 | 見逃し: 経過が BD の遅い側の幅を超えたら POOR（ちょうどはまだ） |
//! | DOM-LR2-01 | LR2 の判定幅: `#RANK` 0/1/3 は PG/GR/GD = 8/24/40・15/30/60・21/60/120ms、それ以外（既定 2）は 18/40/100ms。BD ±200ms、空POOR は早 1000ms 未満。皿も同じ。bmson は既定 |
//! | DOM-LR2-02 | LR2 の TOTAL: 整数に切り捨て。1 未満・無しなら n < 400: n/5+200、n < 600: (n−400)/2.5+280、他: (n−600)/5+360 に × 0.8 して切り捨て |
//! | DOM-LR2-03 | LR2 のダメージ係数 = max(ノーツ数の段階 × 10, 100 / 回復値) / 10。回復値 = ⌊(TOTAL − 80) × 0.125 / 2⌋（0 以下は 1） |
//! | DOM-LR2-04 | LR2 のゲージ: 初期値 GROOVE/EASY 20・他 100、判定ごとの増減表（GROOVE/HARD/DEATH/EASY/P-ATTACK/G-ATTACK）。ASSIST EASY・EX-HARD は無し |
//! | DOM-LR2-05 | LR2 のゲージ更新: 更新前の値を偶数に切り捨てて 30 以下なら GROOVE/EASY 以外の BD/PR/空POOR は × 0.6。GROOVE/EASY は 2 で止まる。0..=100 に収め、更新前の切り捨て値が 0 以下なら 0 |
//! | DOM-LR2-06 | LR2 のクリア: HARD・G-ATTACK・P-ATTACK は 2 以上、それ以外は 80 以上 |
//! | DOM-BRJ-01 | beatoraja の判定倍率: `#RANK` 0..=4 は 25/50/75/100/125%、範囲外・無しは 75%。bmson `judge_rank` は 0 未満 75%、5 未満は `#RANK` 扱い、他はそのまま %（優先） |
//! | DOM-BRJ-02 | beatoraja の 7 鍵判定幅 = 基準 × 倍率（PG..BD、µs 切り捨て）。空POOR は固定。皿は別の基準 |
//! | DOM-BRJ-03 | beatoraja の TOTAL: `#TOTAL` が正ならそのまま、bmson `total` が正なら % × 既定値（優先）、他は既定値 max(260, 7.605n / (0.01n + 6.5)) |
//! | DOM-BRJ-04 | beatoraja の 7 鍵ゲージ: 初期値・ボーダー・増減表。EASY 系の増加は × TOTAL / n、HARD/EX-HARD の増加は × min(0.15, (2·TOTAL − 320) / n) / 0.15。P-ATTACK・G-ATTACK は無し |
//! | DOM-BRJ-05 | beatoraja のゲージ更新: 減少時は「値 < 閾値」の最初の行の倍率（HARD）。最小（EASY 系 2、他 0）..100 に収め、0 になったら以後動かない |
//! | DOM-BRJ-06 | beatoraja のクリア: 値が 0 より大きくボーダー以上 |
//! | DOM-LRP-01 | LR2 のレーン配置: 時刻順に並べ、同じレーンで直前と同時刻のものは捨てる（LN は直前の通常ノーツを置き換える）。直前が LN なら終端以前に始まるものは捨てる。地雷は並ぶがノーツ数に入れない。不可視は入れない |
//! | DOM-LRP-02 | LR2 の押下: 押したフレームで先頭ノーツを判定し PG〜BD なら片付ける。差 = フレーム時刻 − ⌊ノーツ時刻⌋（ms）。BD のときは次のノーツが ±BD 内なら同じ押下で続けて判定する |
//! | DOM-LRP-03 | LR2 の空POOR: 先頭ノーツ（通常・LN）に当たらず早 1000ms 未満なら空POOR。ノーツは残る。レーンが空なら何もしない |
//! | DOM-LRP-04 | LR2 の見逃し: フレーム時刻 − ノーツ時刻が、通常ノーツは BD を、押していない LN は GD を超えたら POOR |
//! | DOM-LRP-05 | LR2 の LN: 押したフレームで始点の判定を保留し、押し続けて ⌊終端⌋ を過ぎたフレームでその判定。離したフレームで フレーム時刻 + GD < ⌊終端⌋ なら BAD、そうでなければ始点の判定 |
//! | DOM-LRP-06 | LR2 の地雷: 押したフレームで 地雷 − フレーム時刻 < GR（過ぎていても）なら発動。地雷を過ぎたフレームで押下中なら発動、押していなければ消える。発動で HP − 生の値（GROOVE/EASY は 2 で止まる）、POOR +1 |
//! | DOM-LRP-07 | LR2 のコンボ: PG/GR/GD で +1、BD/POOR で 0、空POOR・地雷では変わらない。最大コンボを記録 |
//! | DOM-LRP-08 | LR2 の終了: 全ノーツを処理したら終了。フレームの終わりにゲージが 2 未満なら途中終了し、以後のフレームは無視（同じフレームの残りのレーンは処理する） |
//! | DOM-LRP-09 | LR2 のランプ: 最大コンボ = 総ノーツ数なら FULL COMBO。全ノーツ処理済みでクリア条件（DOM-LR2-06）を満たせば HARD・G-ATTACK・P-ATTACK は HARD、EASY は EASY、他は NORMAL。それ以外は FAILED |
//! | DOM-LRP-10 | LR2 の記録: EX スコア = PG×2 + GR、最小 BP = BD + POOR、プレイ回数 1 |
//! | DOM-LRP-11 | LR2 のフレーム処理: フレームごとに時刻（整数 ms）と各レーンの状態（押した・押し続け・離した・なし）を受け、レーンを番号順に 1 回ずつ処理する。1 レーンで片付くのは先頭ノーツ 1 つ（BD の続け判定を除く） |
//! | DOM-LRP-12 | LR2 のキー音: レーンのキー音は最初のノーツの音で始まり、片付いたノーツ（見逃しを含む）の音に替わる。押したとき、判定（空POOR を含む）したノーツがあればその音、無ければレーンのキー音を鳴らす。地雷・離し・見逃しでは鳴らさない |
//! | DOM-LRP-13 | LR2 の BGM・不可視ノーツ: フレーム時刻より前になったフレームで、レーンより先に時刻順（同時刻は記述順）に処理する。BGM は鳴らし、不可視ノーツはそのレーンのキー音を差し替える |
//! | DOM-LRP-14 | 描画用のノーツ: まだ片付いていないもの（地雷を含む）をレーン順・時刻順に返し、押下中の LN は押下中とする |
//! | DOM-LRP-15 | LR2 のオートプレイ: オブジェクトは通常と同じに処理し、各レーンで判定時刻以下のノーツをすべて PG にする（LN は始点で押下中・終端で PG）。地雷は発動させずに消す。キー音は片付けたノーツ（LN は始点）の音 |
//! | DOM-SPD-01 | LR2 の HS-FIX の倍率: OFF・CONSTANT は 1、それ以外は 150 / BPM。BPM はノーツ（通常・LN の始点）の位置の BPM の最大・最小（初期 BPM から）・平均・最多（同数は先に現れたもの）。ノーツが無ければ平均・最多は 1 |
//! | DOM-SPD-02 | LR2 のノーツの位置: CONSTANT 以外は 拍 × 480、CONSTANT は止まっていない経過時間（ms）× 1.2。表示は 位置の差 × ハイスピード × 倍率 / 600 ピクセル |
//! | DOM-SKD-01 | LR2 スキンの条件: 0 は真、正はその条件、負は否定。1000 以上は偽（否定なら真） |
//! | DOM-SKD-02 | LR2 のキーフレームを引く時刻: 始端 ≤ 終端・t ≥ 始端・（ループ ≥ 0 か t ≤ 終端）のときだけ描く。始端 = 終端 かループ = 終端なら終端で止め、ループ < 終端なら [ループ, 終端) で繰り返し、ループ > 終端なら 0。止まっているタイマーは −1 |
//! | DOM-SKD-03 | LR2 のキーフレーム補間: 時刻以下で最後のキーフレームから次へ、その加速で補間（0 線形、1 r³、2 1−(1−r)³、他は止める）。位置・大きさ・色・角度を補間し、合成・中心・フィルタは選んだキーフレームのもの |
//! | DOM-SKD-04 | LR2 の切り出し: コマ = (経過 % 周期) × コマ数 / 周期（経過 < 0・周期 ≤ 0 は 0）。左上から行ごとに数え、大きさは 幅/分割 の切り捨て。幅・高さが負なら画像全体。SRC と DST のタイマーが同じなら経過から最初のキーフレームの時刻を引く |
//! | DOM-SKD-05 | LR2 の四角形: α < 2 で合成ありなら描かない。負の幅・高さは位置をずらして正にする |
//! | DOM-SKD-06 | LR2 の数字: コマ数 10 の倍数 = 0-9（空白は描かない）、11 の倍数 = 10 番が空白、24 の倍数 = 符号付き（11 = +、23 = −、負の数字は +12）。揃え 0 = 右（下位桁を残す）、1 = 左、2 = 中央。負の値は 24 の倍数だけ。分からない数値は −1 |
//! | DOM-SKD-07 | LR2 の要素: IMAGE・NUMBER・BARGRAPH・SLIDER は条件をすべて満たすときだけ描く。DST 引数 21 が 1/2 の IMAGE は皿の角度で回す。BARGRAPH は値で幅か高さを縮め、SLIDER は 値 × 範囲 だけずらす。描画順キーの小さい順（同じなら並び順） |
//! | DOM-SKD-08 | LR2 のゲージ: 50 区間を SRC 引数 1, 2 ずつずらして描く。GROOVE 系は 1..39 区間目が 点灯 1 / 消灯 3、以降は 0 / 2。HARD 系はすべて 0 / 2。HP/2 − 乱数(0..=2) 以上 HP/2 未満（1 区間目を除く）はちらついて消灯 |
//! | DOM-SKD-09 | LR2 の NOWJUDGE: 添字 5=PG … 1=POOR, 0=空POOR の 1 つをタイマー 46 で、プレイ開始（タイマー 41 > 0）後に描く。コンボは GD 以上のときだけ判定の位置からの相対で描き、SRC 引数 1 が 0 なら判定を 桁数 × 幅/2 左へ、そうでなければコンボを (桁数 − 1) × 幅/2 左へ |
//! | DOM-SKD-10 | LR2 のノーツ: DST_NOTE の位置から 拍数 × 480 × ハイスピード / 600 上に描く（過ぎたものは判定位置）。α 255・Alpha 合成。LN は 胴・終端・始端 の順、押していない LN はコマ 0。プレイ開始後だけ |
//! | DOM-SKD-11 | LR2 の小節線: DST_LINE の位置から 拍数 × 480 × ハイスピード / 600 上に、判定位置を過ぎていないものだけ α 255 で描く。プレイ開始後だけ |
//! | DOM-SKD-12 | LR2 の文字列: DST の幅・高さが 0 でなく文字列が空でないときだけ、同じ番号の画像フォント（大きさ > 0）で、無ければ同じ番号のシステムフォントで描く。DST の角度は使わない |
